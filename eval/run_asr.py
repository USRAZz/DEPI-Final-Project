"""Run the attack suite with the controls on and off and report the attack success rate (owner: M4 Ziad).

    python eval/run_asr.py                       # in-memory cases; SQL cases need a database:
    ASR_DATABASE_URL=postgresql+psycopg://postgres:pw@localhost:5432/postgres python eval/run_asr.py
    python eval/run_asr.py --report eval/ASR_REPORT.md --json eval/results/asr.json
    python eval/run_asr.py --fail-on-new         # exit 1 if an attack gets through that is not a documented gap

ASR = attacks that succeeded / attacks run. See eval/asr_harness.py for what "controls on/off" means.
The SQL cases create (and drop and recreate) a database called securefin_asr on that server.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys
from collections import Counter, defaultdict
from datetime import UTC, datetime

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import asr_harness  # noqa: E402

LABELS = {"prompt_injection": "A. Prompt injection", "self_approval": "B. Self-approval / approval abuse",
          "iban_swap": "C. Bank-detail (IBAN) swap", "audit_tamper": "D. Audit / approval tampering"}


def summarize(results):
    by_cat = defaultdict(lambda: {"run": 0, "on": 0, "off": 0, "skipped": 0, "expected_match": 0})
    for r in results:
        s = by_cat[r.case["category"]]
        if r.skipped:
            s["skipped"] += 1
            continue
        s["run"] += 1
        s["on"] += r.on.succeeded(r.case)
        s["off"] += r.off.succeeded(r.case)
        s["expected_match"] += r.on.outcome == r.case["expected"]
    total = {k: sum(s[k] for s in by_cat.values()) for k in ("run", "on", "off", "skipped", "expected_match")}
    return dict(by_cat), total


def _pct(n, d):
    return f"{100 * n / d:.1f}%" if d else "n/a"


def markdown(results) -> str:
    by_cat, total = summarize(results)
    lines = [
        "# Attack suite results",
        "",
        f"Generated by `eval/run_asr.py` on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC. "
        "Do not edit by hand: re-run the script.",
        "",
        "ASR = attacks that succeeded / attacks run. **Controls on** is the system as built; **controls off** "
        "removes the gateway, the database roles and row-level security, the append-only trigger and the "
        "hash-chain check (extractor checks and risk features still run). The AI is assumed fully hijacked: "
        "each case states what the injected model emits. See `eval/asr_harness.py`.",
        "",
        "| Category | Cases run | ASR controls off | ASR controls on | Outcome = expected (on) | Not run |",
        "|---|---|---|---|---|---|",
    ]
    for cat, label in LABELS.items():
        s = by_cat.get(cat, {"run": 0, "on": 0, "off": 0, "skipped": 0, "expected_match": 0})
        lines.append(f"| {label} | {s['run']} | {s['off']}/{s['run']} ({_pct(s['off'], s['run'])}) | "
                     f"{s['on']}/{s['run']} ({_pct(s['on'], s['run'])}) | {s['expected_match']}/{s['run']} | {s['skipped']} |")
    lines.append(f"| **All** | **{total['run']}** | **{total['off']}/{total['run']} ({_pct(total['off'], total['run'])})** | "
                 f"**{total['on']}/{total['run']} ({_pct(total['on'], total['run'])})** | "
                 f"{total['expected_match']}/{total['run']} | {total['skipped']} |")
    lines += ["", "## Cases", "", "| Case | Category | Expected | On | Off | Attack succeeded (on / off) | Notes |",
              "|---|---|---|---|---|---|---|"]
    for r in results:
        c = r.case
        if r.skipped:
            lines.append(f"| {c['id']} | {c['category']} | {c['expected']} | not run | not run | – | {r.skipped} |")
            continue
        on_s, off_s = r.on.succeeded(c), r.off.succeeded(c)
        note = "; ".join(r.on.notes)[:140].replace("|", "/")
        lines.append(f"| {c['id']} | {c['category']} | {c['expected']} | {r.on.outcome} | {r.off.outcome} | "
                     f"{'**YES**' if on_s else 'no'} / {'yes' if off_s else 'no'} | {note} |")
    gaps = [r for r in results if not r.skipped and r.on.succeeded(r.case) and r.case["attack"].get("known_gap")]
    if gaps:
        lines += ["", "## Known gaps (attacks that get through with the controls on)", ""]
        lines += [f"- **{r.id}** {r.case['description']}: {r.case['attack']['known_gap']}" for r in gaps]
    skipped = Counter(r.skipped for r in results if r.skipped)
    if skipped:
        lines += ["", "## Not run", ""] + [f"- {n} case(s): {why}" for why, n in skipped.items()]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--report", help="write the markdown report here")
    ap.add_argument("--json", help="write per-case results as JSON here")
    ap.add_argument("--max-asr-on", type=float, help="fail if ASR with the controls on is above this (0-1)")
    ap.add_argument("--fail-on-new", action="store_true",
                    help="fail if an attack gets through with the controls on and the case has no `known_gap`")
    ap.add_argument("--case", nargs="*", help="only these case ids")
    args = ap.parse_args(argv)

    cases = asr_harness.load_cases()
    if args.case:
        cases = [c for c in cases if c["id"] in set(args.case)]
    results = asr_harness.run_all(cases)
    report = markdown(results)
    if args.report:
        pathlib.Path(args.report).write_text(report, encoding="utf-8")
    if args.json:
        out = pathlib.Path(args.json)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps([{
            "id": r.id, "category": r.case["category"], "expected": r.case["expected"], "skipped": r.skipped,
            "on": None if r.skipped else {"outcome": r.on.outcome, "succeeded": r.on.succeeded(r.case),
                                          "happened": sorted(r.on.happened), "notes": r.on.notes},
            "off": None if r.skipped else {"outcome": r.off.outcome, "succeeded": r.off.succeeded(r.case),
                                           "happened": sorted(r.off.happened)},
        } for r in results], indent=2, ensure_ascii=False), encoding="utf-8")
    _, total = summarize(results)
    print(f"cases run: {total['run']}, not run: {total['skipped']}")
    print(f"ASR controls off: {total['off']}/{total['run']} ({_pct(total['off'], total['run'])})")
    print(f"ASR controls on:  {total['on']}/{total['run']} ({_pct(total['on'], total['run'])})")
    new = []
    for r in results:
        if not r.skipped and r.on.succeeded(r.case):
            gap = r.case["attack"].get("known_gap")
            print(f"  GOT THROUGH: {r.id} {r.case['description']} -> {sorted(r.on.happened)}"
                  + (" [known gap]" if gap else " [NEW]"))
            if not gap:
                new.append(r.id)
    if args.fail_on_new and new:
        return 1
    if args.max_asr_on is not None and total["run"] and total["on"] / total["run"] > args.max_asr_on:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
